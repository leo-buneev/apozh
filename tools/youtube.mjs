// Finds a YouTube video for every song in songs.js and the chorus start time,
// and writes youtube.js. Run: node tools/youtube.mjs  (re-runs reuse tools/youtube-cache.json)
//
// Video: the first of the top search results that is 1:20–9:00 long and allows embedding.
// Chorus: the peak of YouTube's "most replayed" heatmap, skipping the intro and outro
// (the heatmap always spikes at 0:00). Starts a few seconds before the peak.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SONG_CATEGORIES } from '../songs.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CACHE = `${ROOT}tools/youtube-cache.json`;
const HEADERS = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36',
  'Accept-Language': 'ru,en;q=0.8',
  Cookie: 'CONSENT=YES+1; SOCS=CAI',
};
const LEAD_IN_SECONDS = 3;

async function get(url) {
  // YouTube drops connections when hit too fast; back off and retry.
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const res = await fetch(url, { headers: HEADERS });
      if (res.ok) return res.text();
    } catch {}
    await new Promise((r) => setTimeout(r, 2000 * 2 ** attempt));
  }
  throw new Error(`GET ${url} failed`);
}

function initialData(html) {
  const m = html.match(/var ytInitialData = (\{.*?\});<\/script>/s);
  return m ? JSON.parse(m[1]) : null;
}

function* walk(node, key) {
  if (!node || typeof node !== 'object') return;
  if (node[key]) yield node[key];
  for (const v of Object.values(node)) yield* walk(v, key);
}

function seconds(text) {
  return (text || '').split(':').reduce((acc, part) => acc * 60 + Number(part), 0);
}

async function search(query) {
  const html = await get(`https://www.youtube.com/results?search_query=${encodeURIComponent(query)}`);
  const data = initialData(html);
  const out = [];
  for (const v of walk(data, 'videoRenderer')) {
    if (!v.videoId || out.some((x) => x.id === v.videoId)) continue;
    out.push({ id: v.videoId, title: v.title?.runs?.map((r) => r.text).join('') ?? '', length: seconds(v.lengthText?.simpleText) });
    if (out.length >= 6) break;
  }
  return out;
}

async function inspect(id) {
  const html = await get(`https://www.youtube.com/watch?v=${id}`);
  const embeddable = /"playableInEmbed":true/.test(html);
  const markers = [...html.matchAll(/"startMillis":"(\d+)","durationMillis":"(\d+)","intensityScoreNormalized":([0-9.e-]+)/g)]
    .map((m) => ({ start: Number(m[1]) / 1000, dur: Number(m[2]) / 1000, v: Number(m[3]) }));
  return { embeddable, markers: markers.slice(0, 100) };
}

function chorusStart(markers, length) {
  if (markers.length < 20) return null;
  const from = Math.max(15, length * 0.12);
  const to = length * 0.92;
  let best = null;
  for (let i = 1; i < markers.length - 1; i++) {
    const m = markers[i];
    if (m.start < from || m.start > to) continue;
    const score = markers[i - 1].v + m.v * 2 + markers[i + 1].v; // smooth over neighbours
    if (!best || score > best.score) best = { score, start: m.start };
  }
  return best ? Math.max(0, Math.round(best.start - LEAD_IN_SECONDS)) : null;
}

async function resolve(song) {
  const query = song.replace(/\s*\(.*\)\s*$/, '').replace(' — ', ' ');
  const results = await search(query);
  let fallback = null;
  for (const r of results.filter((x) => x.length >= 80 && x.length <= 540).slice(0, 3)) {
    const info = await inspect(r.id);
    if (!info.embeddable) { fallback ??= r; continue; }
    return { id: r.id, title: r.title, start: chorusStart(info.markers, r.length), embed: true };
  }
  const r = fallback ?? results[0];
  return r ? { id: r.id, title: r.title, start: null, embed: false } : null;
}

const cache = JSON.parse(await readFile(CACHE, 'utf8').catch(() => '{}'));
const songs = SONG_CATEGORIES.flatMap((c) => c.songs);
const todo = songs.filter((s) => !cache[s]); // also retries earlier failures
let done = 0;
async function worker() {
  while (todo.length) {
    const song = todo.shift();
    try {
      cache[song] = await resolve(song);
    } catch (e) {
      console.error('failed:', song, e.message);
    }
    if (++done % 20 === 0) {
      console.log(`${done} done`);
      await writeFile(CACHE, JSON.stringify(cache, null, 1));
    }
  }
}
await Promise.all(Array.from({ length: 2 }, worker));
await writeFile(CACHE, JSON.stringify(cache, null, 1));

const lines = songs.filter((s) => cache[s]).map((s) => {
  const r = cache[s];
  return `  ${JSON.stringify(s)}: [${JSON.stringify(r.id)}, ${r.start ?? 0}${r.embed ? '' : ', false'}],`;
});
await writeFile(`${ROOT}youtube.js`, `// Generated by tools/youtube.mjs: song -> [YouTube id, start second (chorus), embeddable?]\nexport const YOUTUBE = {\n${lines.join('\n')}\n};\n`);
const found = songs.filter((s) => cache[s]);
console.log(`videos: ${found.length}/${songs.length}, chorus: ${found.filter((s) => cache[s].start).length}, not embeddable: ${found.filter((s) => !cache[s].embed).length}`);
